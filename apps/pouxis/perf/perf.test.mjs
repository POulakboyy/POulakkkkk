// Unit tests of the perf tooling’s pure parts: `node --test perf/*.test.mjs`.
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { areaOf, attributeBytes, decodeVlq } from './bundle.mjs';
import { buildDataset, prng } from './seed.mjs';
import { percentile, summariseFrames, summariseLatency } from './stats.mjs';

describe('source map attribution', () => {
  it('decodes VLQ fields, including negative and multi-digit values', () => {
    assert.deepEqual(decodeVlq('AAAA'), [0, 0, 0, 0]);
    assert.deepEqual(decodeVlq('AACD'), [0, 0, 1, -1]);
    assert.deepEqual(decodeVlq('gB'), [16]);
    assert.throws(() => decodeVlq('A!'));
  });

  it('attributes each generated byte range to the source of its segment', () => {
    // Line 0: columns 0–4 from a.ts, 5–end from b.ts. Line 1: all from a.ts.
    const code = 'aaaaabbb\ncc';
    const map = { sources: ['src/a.ts', 'src/b.ts'], mappings: 'AAAA,KCAA;ADAA' };
    const bytes = attributeBytes(code, map);
    assert.equal(bytes.get('src/a.ts'), 5 + 3);
    assert.equal(bytes.get('src/b.ts'), 4);
  });

  it('groups sources by package and app area', () => {
    assert.equal(areaOf('../../node_modules/react-dom/cjs/x.js'), 'react-dom');
    assert.equal(areaOf('../../node_modules/@tauri-apps/api/core.js'), '@tauri-apps/api');
    assert.equal(areaOf('../../packages/core/src/nlp/parse.ts'), '@pouxis/core/nlp');
    assert.equal(areaOf('../../packages/core/src/time.ts'), '@pouxis/core/time');
    assert.equal(areaOf('../../apps/pouxis/src/i18n/fr/nav.ts'), 'src/i18n/fr');
    assert.equal(areaOf('../../apps/pouxis/src/main.tsx'), 'src/main.tsx');
  });
});

describe('frame and latency summaries', () => {
  it('computes nearest-rank percentiles', () => {
    assert.equal(percentile([], 95), 0);
    assert.equal(percentile([5, 1, 3, 2, 4], 50), 3);
    assert.equal(percentile([5, 1, 3, 2, 4], 100), 5);
  });

  it('reports fps and counts frames that missed a vsync', () => {
    const steady = Array.from({ length: 61 }, (_, i) => i * (1000 / 60));
    const smooth = summariseFrames(steady);
    assert.equal(smooth.fps, 60);
    assert.equal(smooth.dropped, 0);
    const janky = summariseFrames([0, 16, 32, 132, 148]);
    assert.equal(janky.dropped, 1);
    assert.equal(janky.maxFrameMs, 100);
    assert.equal(summariseFrames([0]).frames, 0);
  });

  it('merges event entries per interaction and keeps the worst, like INP', () => {
    const events = [
      { id: 1, duration: 24 },
      { id: 1, duration: 40 },
      { id: 2, duration: 32 },
      { id: 0, duration: 500 }, // not an interaction (e.g. pointermove)
    ];
    assert.deepEqual(summariseLatency(events), { slowInteractions: 2, inpLikeMs: 40, worstMs: 40 });
    assert.deepEqual(summariseLatency([]), { slowInteractions: 0, inpLikeMs: 0, worstMs: 0 });
  });
});

describe('stress data set', () => {
  it('is deterministic and sized as requested', () => {
    assert.equal(prng(1)(), prng(1)());
    const counts = { tasks: 30, events: 20, notes: 10, nodes: 45 };
    const a = buildDataset(counts, 0);
    assert.deepEqual(a, buildDataset(counts, 0));
    assert.equal(a.tasks.length, 30);
    assert.equal(a.events.length, 20);
    assert.equal(a.notes.length, 10);
    assert.equal(a.graph.nodes.length, 45);
  });

  it('builds valid records: events end after they start, edges join existing nodes', () => {
    const data = buildDataset({ tasks: 50, events: 50, notes: 5, nodes: 100 }, 1_800_000_000_000);
    assert.ok(data.events.every((e) => e.end > e.start));
    assert.ok(data.tasks.every((t) => t.status !== 'doing' && Array.isArray(t.timeLogs)));
    const ids = new Set(data.graph.nodes.map((n) => n.id));
    assert.ok(data.graph.edges.every((e) => ids.has(e.from) && ids.has(e.to)));
    assert.equal(data.graph.edges.length, 100 - 5); // one hub per 20 nodes
  });
});
